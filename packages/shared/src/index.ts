// Types and helpers shared by the API, the customer portal and the admin dashboard.
// Money is always integer kobo (₦1 = 100 kobo).

export type OrderStatus = 'pending' | 'success' | 'failed' | 'flagged';

export interface PublicPlan {
  id: string;
  name: string;
  description: string;
  priceKobo: number;
  durationMinutes: number;
  /** Null means unlimited data (a time pass). */
  dataCapMb: number | null;
  /** No voucher codes left, so the plan can't be bought right now. */
  soldOut: boolean;
}

export interface Plan extends PublicPlan {
  active: boolean;
  /** The monthly job tops unused codes up to this many. 0 = no generated codes for this plan. */
  voucherStockTarget: number;
  /** Unused voucher codes loaded for this plan. */
  vouchersAvailable: number;
  sortOrder: number;
  createdAt: string;
  updatedAt: string;
}

